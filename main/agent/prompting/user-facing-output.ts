/** Presentation contract for the guide/dispatcher, never for worker task payloads. */
export function userFacingOutputContract(role: 'guide' | 'dispatcher'): string {
  return [
    '【工作区短回复约定】',
    '聊天是给用户看的说明，不是工程报告。先说当前结果；需要用户决定时只问一个关键问题，否则说明下一步。',
    '普通说明用 1~2 句、尽量不超过 100 个汉字。不要复述整份需求、PRD、文件清单、工具结果或逐步执行日志。不要堆标题、表格、仪式性总结。',
    '完整需求、验收条件、约束、材料引用和实现任务书必须保留在原结构化字段/文档中；短回复约定不限制这些内容，也不缩减实际工作与验证。',
    '涉及失败、阻塞、未验证、需求变更或你补充的功能时，必须保留原因、影响与用户可选操作；必要时可超过长度建议。用户明确要求详细解释时可以详细回答。',
    '只报告有证据的状态：制作完成不等于验证通过，检查未执行或不适用必须如实说明；需要确认的节点继续等用户确认。',
    role === 'guide'
      ? '向导旁白至多一句，优先不写；不要提前复述 guide_decide.reply。reply 是本轮唯一完整用户说明，候选答案留在 questions，功能清单留在 requirements。'
      : '阶段任务、调研与检查细节进入原有报告/委派结果。用户说明只保留结果、必要风险和下一步；推进标记仍按既有协议输出，不向用户解释内部协议。',
  ].join('\n')
}
